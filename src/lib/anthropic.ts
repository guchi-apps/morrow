/**
 * 秘書としての振る舞い（体裁の指示・依頼の文面）の置き場。**サーバー専用。**
 * 人格そのもの（身元の一文・話し方）は `@/lib/persona` にある（#226）。
 *
 * **ファイル名に反して、もうAnthropic SDKは使っていない**（#183で朝の見通しもCodexへ移り、
 * アプリからClaudeを呼ぶ経路が無くなった）。ここに残っているのは提供元に依らない
 * プロンプトだけで、お知らせ選定・朝の見通し・先回りの提案がここから読む（相談は#574で廃止）。
 */

/**
 * 「今日は知らせることが無い」と判断したときにモデルへ返させる合図（#79）。
 *
 * **黙れることがモデルを通す唯一の理由**。定型文で組み立てるだけなら、材料はAIDEが
 * 構造化JSONで返すのでAPI費用は0円で済む。裏を返すと、この合図が効かなければ
 * モデルを通す意味がほとんど無い。
 *
 * 本文へ混ぜず単独で返させるのは、部分一致で判定すると「特に無いと言いたいところですが」の
 * ような文まで黙らせてしまうため。
 */
export const BRIEFING_SKIP_TOKEN = "NO_BRIEFING";

/** 朝の見通しを頼む文面（#79）。実際にモデルへ渡している依頼そのもの。 */
export const MORNING_BRIEFING_REQUEST =
  `おはよう。今日の予定・移動・天気と、部屋やシステム・支払い予定・放置しているセッション・確認待ちに気になることがないかを確かめて、今日の見通しを短くまとめて。`;

/**
 * 朝の見通しで、繋いでいる外部サービスについて添える指示（#79）。
 *
 * 相談の `connectedServiceRules()` を使い回さない。あちらは「尋ねられたら調べる」「登録の前に
 * 復唱して確認する」（#78）という、**相手がその場にいる前提**の指示で、利用者のいない朝の
 * 生成には噛み合わない。復唱しても答える人がいない。
 *
 * **書き込みの道具は設定によらず常に止める**（`toCodexMcpServers(servers, false)`）。
 * 確認を取る相手がいない場面で、取り消せない結果が残る道具を渡す理由が無い。
 *
 * **道具はまとめて一度に呼ばせる**（#183）。Codexへ渡す接続には
 * `supports_parallel_tool_calls=true` が付いている（`src/lib/codex.ts`）が、まとめるかどうかを
 * 決めるのはモデルなので、指示の側にも書く。順に呼ばれると**道具の数だけ往復が増え**、
 * 1回が9秒×10本ぶん伸びる（#131の実測。本数は#296でAIDEの分割に合わせて6本から増えた）。
 */
function briefingServiceRules(labels: string[]): string[] {
  if (labels.length === 0) return [];

  return [
    `${labels.join("・")}に繋がっていて、その中のデータを取ってくる道具が使えます`,
    "必要な道具は順に呼ばず、まとめて一度に呼ぶ。順に呼ぶとそのぶん時間がかかる",
    "記録の追加・登録・変更をする道具は呼ばない。これは利用者のいないところで動いており、確かめる相手がいない",
    "道具を呼ぶ前に「確認します」のような前置きを書かない。本文だけを返す",
  ];
}

/** 朝の見通しの体裁。 */
const BRIEFING_FORMAT_RULES = [
  "本文は200文字以内。端末の通知にそのまま出るため、これより長いと途中で切られる",
  "見出し・箇条書き・表・記号の装飾・URLは使わない。ふつうの文を2〜4文",
  "いちばん今日を左右することから書く。予定が無い日は天気と体調に関わることだけでよい",
  "数字はそのまま書く（気温・時刻・件数）。「やや高め」のような言い換えで具体を消さない",
];

/**
 * 朝の見通しで扱う材料と、本文へ触れる条件（#116）。
 *
 * 200文字の上限がある以上、道具が増えても全部を毎日書けるわけではない。**「毎日必ず書く」と
 * 「条件を満たした日だけ触れる」を分ける。** しきい値をここ（システムプロンプト）に置くのは、
 * `MORNING_BRIEFING_REQUEST` は依頼文なので、数値のような
 * 技術的な詳細を持ち込みたくないため。
 *
 * 道具そのものは条件を満たすかどうかに関わらず毎日呼ぶ（呼ばないと条件を満たすかどうか
 * 判断できない）。触れるかどうかだけが条件で変わる。
 */
export const BRIEFING_MATERIAL_RULES = [
  "予定（aide_schedule。date を省くと今日）、天気（aide_weather）、" +
    "部屋（aide_room_sensors・aide_aircon_status）、" +
    "システム（aide_host_status・aide_uptime_monitors・aide_service_quotas）、" +
    "支払予定（aide_fixed_costs の upcoming）、放置しているセッション（aide_claude_sessions）、" +
    "確認待ちの滞留（aide_dev_status の attention のうち 00.check-user）は、毎日すべて道具で確かめる",
  "予定・天気は毎日必ず本文に書く。それ以外は次の条件を満たしたときだけ本文で触れ、満たさなければ" +
    "道具で確かめていても本文では一切触れない",
  // aide_weather の state が ok 以外は「予報を取れていない」で、そういう天気という意味ではない。
  "天気は aide_weather の state が ok のときだけ書く。ok 以外の日は天気に触れない（雨や晴れと決めつけない）",
  "部屋・システムは、それぞれの道具のどれかの problems に何か入っているときだけ",
  "支払予定は明日までに引き落とされるものがあるときだけ",
  "放置しているセッションは status が waiting かつ statusForMinutes が30分以上のものがあるときだけ",
  "確認待ちの滞留は1件以上あるときだけ",
];

/**
 * 朝の見通しのシステムプロンプト（#79）。
 *
 * **道具を必ず使わせる。** 手元には何の材料も無く、繋いでいる外部サービス（AIDE）から
 * 取ってこないと書けない。相談のときと違って利用者が続きを促せないので、
 * 「取れなかったので分かりません」で終わらせないことも明示する。
 *
 * **#183でCodexへ渡すようになった。** Codexにはシステムプロンプトを別に渡す口が無いので、
 * 呼び出し側（`src/lib/briefing.ts` の `buildBriefingPrompt()`）がこの文面と
 * `MORNING_BRIEFING_REQUEST` を `---` で繋いで1本にする（お知らせ選定の
 * `buildNoticePrompt()` と同じ形）。文面そのものは提供元に依らないので変えていない。
 */
export function briefingSystemPrompt(connectedLabels: string[]): string {
  const rules = [
    ...BRIEFING_MATERIAL_RULES,
    "道具で取れなかった項目は書かない。それらしい数字や予定を作らない",
    `知らせる価値があることが1つも無ければ、本文を書かずに ${BRIEFING_SKIP_TOKEN} とだけ返す。無理に何か書かない`,
    ...briefingServiceRules(connectedLabels),
    ...SECRETARY_VOICE_RULES,
    ...BRIEFING_FORMAT_RULES,
  ];

  const intro = `${SECRETARY_INTRO}\n\n今は朝です。利用者から聞かれる前に、あなたの方から今日の見通しを1本だけ届けます。`;

  return `${intro}\n\n${rules.map((rule) => `- ${rule}`).join("\n")}`;
}

/** 先回りの提案（#325）を頼む文面。 */
export const PROACTIVE_REQUEST = `いまの空き時間や、進行中の用件を見て、先回りで今ならできそうなことを教えて。`;

/**
 * 先回りの提案を書かせるシステムプロンプト（#325）。
 *
 * **希望の読み方と空き時間の扱いは相談側（`suggestionRules()`。#324）と同じ**——通知から開いた会話で
 * 続きを話したときに、通知と相談で言うことが食い違わないようにするため。違うのは、相手がその場に
 * おらず**確かめる相手がいない**こと。だから書き込みの道具は呼ばせず、取得に失敗した回・材料が
 * 揃わない回は黙らせる（`PROACTIVE_SKIP_TOKEN`）。
 *
 * - `kinds`: いま考えてよい種類。オフの種類・曜日で対象外の種類は渡らない
 * - `recentCandidates`: 最近すでに伝えた候補。**同じ候補を繰り返さない**ための材料
 */
export function proactiveSystemPrompt(params: {
  kinds: ProactiveKind[];
  recentCandidates: string[];
  now: Date;
}): string {
  const { kinds, recentCandidates, now } = params;

  const rules = [
    `いまは日本時間の${jstTodayLabel(now)} ${jstTimeLabel(now)}。利用者は画面を開いていません。今ならできること・そろそろ対応したいことを、あなたの方から通知で1件だけ提案します`,
    `考えてよい提案の種類は次の${kinds.length}つだけ。1行目の種類の欄にはこの名前をそのまま書く`,
    ...kinds.map((kind) => `  - ${kind}（${PROACTIVE_KIND_LABELS[kind]}）`),
    "材料はすべて道具で取る。Notionの「いつかやりたいこと」（https://app.notion.com/p/326d8c89a4fc4794932787bded98a99a）と、AIDEの予定・空き時間（aide_schedule）、未完了の用件（aide_dev_status など、取れるAIDEの道具）。必要な道具は順に呼ばず、まとめて一度に呼ぶ",
    "希望の候補にするのはステータスが「やってみたい」「検討中」のものだけ。「達成」「見送り」は出さない。すでに予定に入っている・予定やタスクで完了と確認できるものは出さない。予定の時刻を過ぎたというだけで実施済みとは判断しない",
    "空き時間は本人の予定が入っていない時間だけ。平日の勤務・通勤の時間帯は空きとして数えない。予定の変更やキャンセルでできた空きは、変更を確かめられたときだけ言う",
    "Notion・予定・タスクのどれか1つでも取れなかった（道具が失敗した・configured や complete が false）ときは、「何もない」と解釈せず提案しない",
    ...(recentCandidates.length > 0
      ? [`最近すでに伝えた候補は繰り返さない: ${recentCandidates.join("、")}`]
      : []),
    "記録の追加・登録・変更をする道具は呼ばない。提案するだけで、Notion・カレンダー・タスクへは何も書き込まない",
    `いま伝える理由が無いとき、または材料が揃わないときは、本文を書かずに ${PROACTIVE_SKIP_TOKEN} とだけ返す。無理に何か書かない`,
    "返答の形は次のとおり。1行目は `種類|候補の名前|予定の状態` を「|」で区切る（候補の名前はNotionの項目名かタスク名、予定の状態は空き時間の日付と時間帯）。2行目以降が通知の本文。前置き・道具を呼ぶ前の確認の一言は書かない",
    "本文は200文字以内。なぜ今なのか（空き時間・期限）と、根拠にした項目の名前を入れる。見出し・箇条書き・記号の装飾・URLは使わない",
    ...SECRETARY_VOICE_RULES,
  ];

  return `${SECRETARY_INTRO}\n\n${rules.map((rule) => (rule.startsWith("  - ") ? rule : `- ${rule}`)).join("\n")}`;
}

/**
 * 「いま出すほどのものは無い」と判断したときに返させる合図（#93）。
 *
 * 積まれていても、いま伝える価値が無いものしかない回はある（期限切れ間近でもない・
 * 夜中にどうでもいい報せ）。**黙れることが、溜まったものを機械的に垂れ流さないための唯一の
 * 手立て**で、#79の `NO_BRIEFING` と同じ役割を担う。
 */
export const NOTICE_SKIP_TOKEN = "NO_NOTICE";

/** 「急ぎとして出す」と判断したときに、1行目へ付けさせる印（#93）。 */
export const NOTICE_URGENT_MARK = "URGENT";

/**
 * 積まれたお知らせから1件を選ばせるシステムプロンプト（#93）。
 *
 * **#132で呼び出し先はCodexへ移ったが、この文面はそのまま使っている**（体裁の指示は提供元に
 * 依らない）。このモジュールに置いたままなのは、朝の見通しと同じ「秘書としての振る舞い」
 * （`SECRETARY_INTRO`）を共有しているため。**Anthropic SDKを使うかどうかとは無関係**——
 * 相談の `secretarySystemPrompt()` もCodexへ渡すためにここから読んでいる。
 *
 * **上限トークンの指定は無い。** `codex exec` に `max_tokens` に当たる引数が無いため、
 * 長さの歯止めは下の「40文字前後」「3行目以降は書かない」だけになった。
 *
 * **道具は渡さない。** 材料はすべて積まれた本文の中にあり、外部サービスを見に行く必要が無い。
 * 渡すと1回あたりの待ち時間がそのぶん増える（この経路は1日に何度も走る）。
 *
 * 返させる形を1行目・2行目に固定してあるのは、JSONを求めると前置きや```で包む揺れが出て、
 * そのたびに吹き出しが黙るため。**知らない形で返ってきた回は黙る**側へ倒してある。
 */
export function noticeSystemPrompt(): string {
  const rules = [
    "渡された候補の中から、いま利用者へ伝える価値がいちばん高いものを1つだけ選ぶ",
    "選ぶ基準は「逃すと困るか」。時間で意味が変わるもの・締め切りが近いものを、いつ言っても同じものより優先する",
    `いま伝える価値のあるものが1つも無ければ ${NOTICE_SKIP_TOKEN} とだけ返す。候補があるからといって無理に選ばない`,
    "候補に無いことを足さない。日時・数量・名前は候補の本文にあるものをそのまま使う",
    "1行目は「選んだ候補の番号」だけを書く。時間を逃すと意味が無くなるものを選んだときは、" +
      `番号の後ろに半角スペースを空けて ${NOTICE_URGENT_MARK} と書く`,
    "2行目に、画面の吹き出しへ出す文をそのまま書く。40文字前後・長くても2文",
    ...SECRETARY_VOICE_RULES,
    "見出し・箇条書き・記号の装飾・URL・絵文字は使わない。画面の狭い吹き出しに1〜2行で収まる文にする",
    "3行目以降は書かない。前置きも説明も付けない",
  ];

  const intro = `${SECRETARY_INTRO}\n\n利用者はMorrowの画面を開いて待っています。各アプリから届いた「知らせたいこと」の候補をこれから渡すので、その中から1つ選び、あなたの言葉で短く伝えてください。`;

  return `${intro}\n\n${rules.map((rule) => `- ${rule}`).join("\n")}`;
}
